    hb_present <= vin_present; hb_locked <= vin_lock_s(1);
    hb_ht <= vin_ht; hb_vt <= vin_vt; hb_ha <= vin_ha; hb_va <= vin_va; hb_hz <= vin_hz;
    hb_hdmi <= vin_hdmi_s(1); hb_island <= vin_island_s(1);
  end generate;
  -- ... or, with the shield receivers (issue 0049 gate build), the first
  -- present one of on-board, HDMI1, HDMI2, HDMI3. Header receivers use the
  -- PLLE2 + BUFG dvi2rgb variant: one CMT per clock region and two of them
  -- share bank 16, so no BUFIO/BUFR. HDMI1/HDMI2 (bank 16, whose PLL is
  -- taken) reach a PLL elsewhere through a BUFG; HDMI3 (bank 15) uses its
  -- own region's free PLL over the dedicated route. HPD and +5V sense go
  -- through the shield's I2C expander (not here yet).
  g_hb_shield : if SHIELD_RX > 0 generate
    type u16_arr is array (natural range <>) of unsigned(15 downto 0);
    type u32_arr is array (natural range <>) of unsigned(31 downto 0);
    constant CLKIN_BUFG : std_logic_vector(0 to 2) := "110";
    -- IDELAYCTRL per clock region: HDMI1+HDMI2 share bank 16 (X0Y2) and
    -- HDMI1's controller, HDMI3 has its own in bank 15 (X0Y1)
    constant IDC_OWN : std_logic_vector(0 to 2) := "101";
    type grp_arr is array (0 to 2) of string(1 to 10);
    constant GRP : grp_arr := ("shd_b16_dg", "shd_b16_dg", "shd_b15_dg");
    signal s_pclk, s_de, s_hs, s_vs, s_lk, s_hd, s_is, s_pr : std_logic_vector(0 to SHIELD_RX - 1);
    signal s_ht, s_vt, s_ha, s_va : u16_arr(0 to SHIELD_RX - 1);
    signal s_hz : u32_arr(0 to SHIELD_RX - 1);
    signal s_lk1, s_lk2, s_hd1, s_hd2, s_is1, s_is2 : std_logic_vector(0 to SHIELD_RX - 1) := (others => '0');
    signal all_present : std_logic_vector(SHIELD_RX downto 0);
    signal all_meas : std_logic_vector((SHIELD_RX + 1) * MEAS_W - 1 downto 0);
    attribute ASYNC_REG of s_lk1, s_lk2, s_hd1, s_hd2, s_is1, s_is2 : signal is "TRUE";
  begin
    g_rx : for i in 0 to SHIELD_RX - 1 generate
      srx : entity work.hdmi_rx_xc7
        generic map (PLL_BUFG => true, CLKIN_BUFG => CLKIN_BUFG(i) = '1',
                     IODELAY_GROUP => GRP(i), IDELAYCTRL => IDC_OWN(i) = '1')
        port map (tmds_clk_p => shd_clk_p(i), tmds_clk_n => shd_clk_n(i),
                  tmds_p => shd_d_p(3 * i + 2 downto 3 * i), tmds_n => shd_d_n(3 * i + 2 downto 3 * i),
