library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use work.xc7_prims_pkg.all;
use work.build_id_pkg.all;   -- generated by the Makefile
use work.common_pkg.all;

entity mimas_a7_top is
  generic (
    RX_PHASE_STEPS : integer := 22;    -- RGMII RX clock phase, 5.625 deg steps (issue 0019 scan)
    -- HDMI OUT sends HDMI (video guard bands, AVI + SPD InfoFrames, issue
    -- 0037); false = the original pure DVI stream
    HDMI_OUT       : boolean := true;
    CON_VIC        : natural := 3        -- console 720x480p60: VIC 3 (16:9), 2 = 4:3
  );
  port (
    clk100       : in    std_logic;
    -- Ethernet (RTL8211E)
    phy_rst_n    : out   std_logic;
    phy_mdc      : out   std_logic;
    phy_mdio     : inout std_logic;
    rgmii_txc    : out   std_logic;
    rgmii_tx_ctl : out   std_logic;
    rgmii_txd    : out   std_logic_vector(3 downto 0);
    rgmii_rxc    : in    std_logic;
    rgmii_rx_ctl : in    std_logic;
    rgmii_rxd    : in    std_logic_vector(3 downto 0);
    -- front panel
    led          : out   std_logic_vector(7 downto 0);
    dip          : in    std_logic_vector(7 downto 0);
    btn          : in    std_logic_vector(3 downto 0);
    seg          : out   std_logic_vector(7 downto 0);
    seg_en       : out   std_logic_vector(3 downto 0);
    -- HDMI OUT (text display, ADR 0012)
    hdmi_tx_p    : out   std_logic_vector(2 downto 0);
    hdmi_tx_n    : out   std_logic_vector(2 downto 0);
    hdmi_tx_clk_p, hdmi_tx_clk_n : out std_logic;
    -- HDMI IN (DVI sink, issue 0022)
    hdmi_rx_p    : in    std_logic_vector(2 downto 0);
    hdmi_rx_n    : in    std_logic_vector(2 downto 0);
    hdmi_rx_clk_p, hdmi_rx_clk_n : in std_logic;
    hdmi_rx_hpa  : out   std_logic;
    hdmi_rx_scl  : in    std_logic;    -- DDC: EDID served at 0x50 (issue 0033)
    hdmi_rx_sda  : inout std_logic;
    -- USB UART (FTDI channel A), unused in phase 1
    usb_uart_tx  : out   std_logic;
    usb_uart_rx  : in    std_logic;
    -- DUT0 (P12) / DUT1 (P13): J block
    dut0_tck, dut0_tms, dut0_tdi, dut0_uart_to : out std_logic;
    dut0_tdo, dut0_uart_from, dut0_vio_sense   : in  std_logic;
    dut1_tck, dut1_tms, dut1_tdi, dut1_uart_to : out std_logic;
    dut1_tdo, dut1_uart_from, dut1_vio_sense   : in  std_logic;
    -- physical keyboard (master), P12 X block: MK-I push-pull clock/data or
    -- MK-II I2C SDA/SCL (open drain), auto-detected (issue 0009)
    pk_kio8, pk_kio9 : inout std_logic;
    pk_kio10         : in  std_logic;
    -- K block
    dut0_kio8, dut0_kio9, dut0_kb_sense : in  std_logic;
    dut0_kio10                          : out std_logic;
    dut1_kio8, dut1_kio9, dut1_kb_sense : in  std_logic;
    dut1_kio10                          : out std_logic
  );
end entity;

architecture rtl of mimas_a7_top is
  signal clk_sys, clk_tx90, clk_ref, locked, clk_rx : std_logic;
  signal rx_dv, rx_er, tx_en : std_logic;
  signal rxd, txd : std_logic_vector(7 downto 0);
  signal jtck, jtms, jtdi, jtdo, joe, utx, uoe, urx : std_logic_vector(1 downto 0);
  signal kio8, kio9, kio10, kio10_oe, vio, kbs : std_logic_vector(1 downto 0);
  signal pk8_o, pk9_o, pk8_oe, pk9_oe : std_logic;
  signal core_leds : std_logic_vector(7 downto 0);
  signal rst_cnt : unsigned(21 downto 0) := (others => '0');
  signal phy_rst : std_logic := '0';
  signal rx_locked, rx_ps_en, rx_ps_done : std_logic;
  signal dna : std_logic_vector(63 downto 0);
  signal clk100_g : std_logic;
  signal con_screen : unsigned(1 downto 0);
  signal con_slots : std_logic_vector(9 downto 0);
  signal vin_pclk, vin_de, vin_hs, vin_vs, vin_locked, vin_present : std_logic;
  signal vin_rgb : std_logic_vector(23 downto 0);
  signal vin_ht, vin_vt, vin_ha, vin_va : unsigned(15 downto 0);
  signal vin_hz : unsigned(31 downto 0);
  signal vin_lock_s : std_logic_vector(1 downto 0) := "00";
  signal vin_hdmi, vin_island : std_logic;
  signal vin_hdmi_s, vin_island_s : std_logic_vector(1 downto 0) := "00";
  signal idc_rdy : std_logic;
  signal good, bad : unsigned(15 downto 0);
  signal link_flags : std_logic_vector(7 downto 0);
  -- video
  signal clk_pix, vlocked, vrst : std_logic;
  -- HDMI OUT passthrough (issue 0032)
  signal con_pix_raw, con_pix5_raw, tx_pix, tx_pix5 : std_logic;
  signal pt_req, pt_sel, pt_rst, pt_active, pt_pll_locked, pt_pll_rst, pt_pll_rst_a : std_logic;
  signal p_rgb : std_logic_vector(23 downto 0) := (others => '0');
  signal p_de, p_hs, p_vs : std_logic := '0';
  signal o_r, o_g, o_b : std_logic_vector(7 downto 0);
  signal o_de, o_hs, o_vs : std_logic;
  signal vx, vy : unsigned(10 downto 0);
  signal v_de, v_hs, v_vs, v_fs, t_de, t_hs, t_vs, t_force : std_logic;
  signal t_r, t_g, t_b : std_logic_vector(7 downto 0);
  signal text_we : std_logic;
  signal text_addr : unsigned(14 downto 0);
  signal text_data : std_logic_vector(7 downto 0);
  signal src0, src1 : std_logic_vector(7 downto 0);
  signal ep_en : std_logic_vector(1 downto 0);
  signal have_ip : std_logic;
  signal vrst_s : std_logic_vector(1 downto 0) := "11";
  signal vid_machine : unsigned(4 downto 0);
  signal vid_machine_ok : std_logic;
  signal tx_vic : std_logic_vector(6 downto 0);
  attribute ASYNC_REG : string;
  attribute ASYNC_REG of vrst_s : signal is "TRUE";
begin
  -- The 100 MHz oscillator (H4) and the HDMI IN clock (K4) share clock region
  -- X1Y1, which has one MMCM; HDMI IN needs it (dedicated route), so the
  -- oscillator reaches its two MMCMs through a BUFG instead (issue 0022).
  bclk100 : BUFG port map (O => clk100_g, I => clk100);
  clk : entity work.clocks_xc7
    port map (clk100 => clk100_g, clk_sys => clk_sys, clk_tx90 => clk_tx90,
              clk_ref => clk_ref, locked => locked);

  idc : IDELAYCTRL port map (RDY => idc_rdy, REFCLK => clk_ref, RST => not locked);

  -- PHY reset: low for ~33 ms after the MMCM locks
  process (clk_sys)
  begin
    if rising_edge(clk_sys) then
      if locked = '0' then
        rst_cnt <= (others => '0');
        phy_rst <= '0';
      elsif rst_cnt(21) = '0' then
        rst_cnt <= rst_cnt + 1;
      else
        phy_rst <= '1';
      end if;
    end if;
  end process;
  phy_rst_n <= phy_rst;
  phy_mdc   <= '0';
  phy_mdio  <= 'Z';

  -- board identity: 57-bit device DNA (issue 0007; 0 until read)
  dnar : entity work.dna_xc7 port map (clk => clk_sys, dna => dna, valid => open);

  phy : entity work.rgmii_xc7
    generic map (RX_PHASE_STEPS => RX_PHASE_STEPS)
    port map (
      clk_sys => clk_sys, clk_tx90 => clk_tx90,
      rgmii_txc => rgmii_txc, rgmii_tx_ctl => rgmii_tx_ctl, rgmii_txd => rgmii_txd,
      rgmii_rxc => rgmii_rxc, rgmii_rx_ctl => rgmii_rx_ctl, rgmii_rxd => rgmii_rxd,
      clk_rx => clk_rx, rx_locked => rx_locked, ps_en => rx_ps_en, ps_done => rx_ps_done,
      rx_dv => rx_dv, rx_er => rx_er, rxd => rxd,
      tx_en => tx_en, tx_er => '0', txd => txd);

  link_flags <= "000000" & '1' & '1' when good /= 0 else x"00";

  core : entity work.supervisor_core
    generic map (CLK_HZ => 125_000_000, BUILD_ID => BUILD_ID)
    port map (
      clk_sys => clk_sys, clk_rx => clk_rx,
      rx_dv => rx_dv, rx_er => rx_er, rxd => rxd, tx_en => tx_en, txd => txd,
      dna => dna, dip => dip, link_flags => link_flags,
      vio_sense => vio, kb3v3_sense => kbs,
      jtck => jtck, jtms => jtms, jtdi => jtdi, jtdo => jtdo, jtag_oe => joe,
      utx => utx, utx_oe => uoe, urx => urx,
      kio8 => kio8, kio9 => kio9, kio10 => kio10, kio10_oe => kio10_oe,
      pk_kio8 => pk8_o, pk_kio9 => pk9_o, pk_kio8_oe => pk8_oe, pk_kio9_oe => pk9_oe,
      pk_kio8_in => pk_kio8, pk_kio10 => pk_kio10,
      buttons => btn, leds => core_leds, text_we => text_we, text_addr => text_addr, text_data => text_data,
      addr_src0 => src0, addr_src1 => src1, ep_enable_o => ep_en,
      stat_rx_good => good, stat_rx_bad => bad,
      rx_ps_en => rx_ps_en, rx_ps_done => rx_ps_done, rx_locked => rx_locked,
      vid_present => vin_present, vid_locked => vin_lock_s(1),
      vid_h_total => vin_ht, vid_v_total => vin_vt, vid_h_active => vin_ha,
      vid_v_active => vin_va, vid_pixel_hz => vin_hz,
      vid_hdmi => vin_hdmi_s(1), vid_islands => vin_island_s(1),
      vin_pclk => vin_pclk, vin_rgb => vin_rgb, vin_de => vin_de, vin_hs => vin_hs,
      vin_vs => vin_vs,
      text_forced => t_force, con_screen => con_screen, con_slots => con_slots,
      pt_request => pt_req, pt_active => pt_active,
      vid_machine => vid_machine, vid_machine_ok => vid_machine_ok);

  -- HDMI IN: DVI sink + measurement for the heartbeat video block (0022)
  hrx : entity work.hdmi_rx_xc7
    port map (tmds_clk_p => hdmi_rx_clk_p, tmds_clk_n => hdmi_rx_clk_n,
              tmds_p => hdmi_rx_p, tmds_n => hdmi_rx_n, hpd => hdmi_rx_hpa,
              ddc_scl => hdmi_rx_scl, ddc_sda => hdmi_rx_sda,
              ref_clk => clk_ref, ref_rst => not locked,
              pclk => vin_pclk, rgb => vin_rgb, de => vin_de, hs => vin_hs, vs => vin_vs,
              locked => vin_locked, hdmi_seen => vin_hdmi, island_seen => vin_island);
  vmeas : entity work.video_meas
    port map (pclk => vin_pclk, de => vin_de, hs => vin_hs, vs => vin_vs, clk => clk_sys,
              h_total => vin_ht, v_total => vin_vt, h_active => vin_ha, v_active => vin_va,
              hs_pol => open, vs_pol => open, frames => open,
              pixel_hz => vin_hz, present => vin_present);
  process (clk_sys)
  begin
    if rising_edge(clk_sys) then
      vin_lock_s <= vin_lock_s(0) & vin_locked;
      vin_hdmi_s <= vin_hdmi_s(0) & vin_hdmi;        -- quasi-static (issue 0040)
      vin_island_s <= vin_island_s(0) & vin_island;
    end if;
  end process;

  ---------------------------------------------------------------- video
  vclk : entity work.clocks_video_xc7
    port map (clk100 => clk100_g, clk_pix => clk_pix, pix_raw => con_pix_raw,
              pix5_raw => con_pix5_raw, locked => vlocked);

  -- HDMI OUT source (issue 0032): the console (local clocks, below) or the
  -- HDMI IN stream passed straight through in its recovered clock domain.
  -- video_pt_ctrl (clk_sys) sequences the glitch-free clock switch with the
  -- TX held in reset; the TX reset is synchronised in the TX serial domain.
  ptc : entity work.video_pt_ctrl
    port map (clk => clk_sys, req => pt_req, vin_locked => vin_locked,
              pll_locked => pt_pll_locked, sel => pt_sel, tx_rst => pt_rst,
              active => pt_active, pll_rst => pt_pll_rst);
  pt_pll_rst_a <= pt_pll_rst or not vin_locked;
  vout : entity work.video_out_clk_xc7
    port map (con_pix => con_pix_raw, con_pix5 => con_pix5_raw, vin_pclk => vin_pclk,
              pll_rst => pt_pll_rst_a, sel => pt_sel, pll_locked => pt_pll_locked,
              tx_pix => tx_pix, tx_pix5 => tx_pix5);
  process (tx_pix5)
  begin
    if rising_edge(tx_pix5) then
      vrst_s <= vrst_s(0) & (pt_rst or not vlocked);
    end if;
  end process;
  vrst <= vrst_s(1);
  -- decoded HDMI IN, registered once in its pixel domain
  process (vin_pclk)
  begin
    if rising_edge(vin_pclk) then
      p_rgb <= vin_rgb; p_de <= vin_de; p_hs <= vin_hs; p_vs <= vin_vs;
    end if;
  end process;
  -- pt_sel only changes while the TX is in reset (video_pt_ctrl)
  o_r  <= p_rgb(23 downto 16) when pt_sel = '1' else t_r;
  o_g  <= p_rgb(15 downto 8)  when pt_sel = '1' else t_g;
  o_b  <= p_rgb(7 downto 0)   when pt_sel = '1' else t_b;
  o_de <= p_de when pt_sel = '1' else t_de;
  o_hs <= p_hs when pt_sel = '1' else t_hs;
  o_vs <= p_vs when pt_sel = '1' else t_vs;
  vtim : entity work.video_timing
    port map (clk => clk_pix, x => vx, y => vy, de => v_de, hs => v_hs, vs => v_vs, frame_start => v_fs);
  text : entity work.text_display
    -- shifted right: the owner's monitor hides the first ~15 px (issue 0027)
    generic map (LEFT => 15,
                 FOOTER => PRODUCT_NAME & " v" & PRODUCT_VERSION & "  build " & hex32(BUILD_ID))
    port map (wr_clk => clk_rx, wr_en => text_we, wr_addr => text_addr, wr_data => text_data,
              clk_pix => clk_pix, x => vx, y => vy, de_in => v_de, hs_in => v_hs, vs_in => v_vs,
              r => t_r, g => t_g, b => t_b, de_out => t_de, hs_out => t_hs, vs_out => t_vs,
              force_text => t_force, screen => con_screen, slots => con_slots);
  -- AVI VIC (issue 0037): the console mode, or for passthrough the CTA code
  -- of the measured HDMI IN geometry (720x480 -> 3, 720x576 -> 18, both
  -- 16:9 like the console; anything else 0 = no VIC). Quasi-static clk_sys
  -- values; the framer samples them per frame (async clock groups).
  tx_vic <= std_logic_vector(to_unsigned(CON_VIC, 7)) when pt_sel = '0' else
            "0000011" when vin_ha = 720 and vin_va = 480 else
            "0010010" when vin_ha = 720 and vin_va = 576 else
            "0000000";
  dvi : entity work.dvi_tx_xc7
    generic map (HDMI => HDMI_OUT)
    port map (pixel_clk => tx_pix, serial_clk => tx_pix5, rst => vrst,
              r => o_r, g => o_g, b => o_b, hs => o_hs, vs => o_vs, de => o_de,
              tmds_p => hdmi_tx_p, tmds_n => hdmi_tx_n,
              tmds_clk_p => hdmi_tx_clk_p, tmds_clk_n => hdmi_tx_clk_n,
              vic => tx_vic, machine => vid_machine, machine_ok => vid_machine_ok);

  have_ip <= '1' when (src0 /= x"00" or ep_en(0) = '0') and (src1 /= x"00" or ep_en(1) = '0') else '0';
  seg7 : entity work.seg7_status
    port map (clk => clk_sys, have_ip => have_ip, id0 => unsigned('0' & dip(3 downto 0)),
              id1 => unsigned('1' & dip(7 downto 4)), seg => seg, seg_en => seg_en);

  -- DUT pins: outputs tri-stated unless the core enables them
  dut0_tck <= jtck(0) when joe(0) = '1' else 'Z';
  dut0_tms <= jtms(0) when joe(0) = '1' else 'Z';
  dut0_tdi <= jtdi(0) when joe(0) = '1' else 'Z';
  dut1_tck <= jtck(1) when joe(1) = '1' else 'Z';
  dut1_tms <= jtms(1) when joe(1) = '1' else 'Z';
  dut1_tdi <= jtdi(1) when joe(1) = '1' else 'Z';
  jtdo <= dut1_tdo & dut0_tdo;
  dut0_uart_to <= utx(0) when uoe(0) = '1' else 'Z';
  dut1_uart_to <= utx(1) when uoe(1) = '1' else 'Z';
  urx <= dut1_uart_from & dut0_uart_from;
  vio <= dut1_vio_sense & dut0_vio_sense;
  kbs <= dut1_kb_sense & dut0_kb_sense;
  kio8 <= dut1_kio8 & dut0_kio8;
  kio9 <= dut1_kio9 & dut0_kio9;
  pk_kio8 <= pk8_o when pk8_oe = '1' else 'Z';
  pk_kio9 <= pk9_o when pk9_oe = '1' else 'Z';
  dut0_kio10 <= kio10(0) when kio10_oe(0) = '1' else 'Z';
  dut1_kio10 <= kio10(1) when kio10_oe(1) = '1' else 'Z';

  -- front panel: green LEDs show the selected target (supervisor_core)
  led <= core_leds;
  usb_uart_tx <= '1';
end architecture;
