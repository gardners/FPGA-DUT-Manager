      vin_lock_s <= vin_lock_s(0) & vin_locked;
      vin_hdmi_s <= vin_hdmi_s(0) & vin_hdmi;        -- quasi-static (issue 0040)
      vin_island_s <= vin_island_s(0) & vin_island;
