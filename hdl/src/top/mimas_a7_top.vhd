entity mimas_a7_top is
  generic (
    RX_PHASE_STEPS : integer := 22;    -- RGMII RX clock phase, 5.625 deg steps (issue 0019 scan)
    -- issue 0036 bring-up without DDR3: 1 = the live select screen reads a
    -- generated test pattern instead of the frame store (machines 0..9 seen,
    -- even ones fresh at 160x100 -> 4x3 thumbnails and colour bars)
    MOSAIC_DEMO    : integer := 0;
    -- HDMI OUT sends HDMI (video guard bands, AVI + SPD InfoFrames, issue
    -- 0037); false = the original pure DVI stream
    HDMI_OUT       : boolean := true;
    CON_VIC        : natural := 3;       -- console 720x480p60: VIC 3 (16:9), 2 = 4:3
    -- issue 0049 shield gate build: number of header HDMI receivers (0 =
    -- none, the normal build; the shd_* ports below then have null range
    -- and vanish). Receiver i = HDMI(i+1) of docs/hardware/shield-pinplan.md,
    -- pins in boards/mimas_a7/shield_v1.xdc. For now their measurements
    -- only reach the heartbeat video block when the on-board input is
    -- idle (vid_src_sel).
    SHIELD_RX      : natural range 0 to 3 := 0
  );
  port (
    clk100       : in    std_logic;
    -- Ethernet (RTL8211E)
    phy_rst_n    : out   std_logic;
    phy_mdc      : out   std_logic;
    phy_mdio     : inout std_logic;
    rgmii_txc    : out   std_logic;
    rgmii_tx_ctl : out   std_logic;
    rgmii_txd    : out   std_logic_vector(3 downto 0);
    rgmii_rxc    : in    std_logic;
    rgmii_rx_ctl : in    std_logic;
    rgmii_rxd    : in    std_logic_vector(3 downto 0);
    -- front panel
    led          : out   std_logic_vector(7 downto 0);
