#!/usr/bin/env python3
"""Rebuild logos/mega-ev.svg (M.E.G.A. e.V. logo) from logos/src/mlogo.png.

The source is a 200 x 52 px raster (see logos/README.md): a 25 x 5 grid of
square blocks (pitch 8 px, black or maroon) spelling "MEGA", and a 6 px tall
line "MUSEUM OF ELECTRONIC GAMES & ART" underneath. Tracing the anti-aliased
pixels gives ragged edges, so the logo is rebuilt as clean vectors:

* blocks: the grid occupancy and colour are read from the PNG (sampled at
  each cell's centre) and drawn as ideal squares (5.75 px on an 8 px pitch,
  measured from the PNG's edge pixels);
* text: the case generator's own 4 x 6 stroke font (casegen/font.py) at the
  original size and width, stroked 1 px wide, then turned into filled
  outlines and unioned by Inkscape (stroke-to-path + union), so the laser
  software sees plain filled shapes without overlaps.

Units: 1 SVG unit = 1 source pixel (viewBox 0 0 200 52). The case generator
scales the logo to its slot. Run: python3 -I tools/make_mega_ev_logo.py
(needs Pillow and inkscape >= 1.2).
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from casegen import font  # noqa: E402

SRC = os.path.join(HERE, 'logos', 'src', 'mlogo.png')
OUT = os.path.join(HERE, 'logos', 'mega-ev.svg')

PITCH, BLOCK, COLS, ROWS = 8.0, 5.75, 25, 5
TEXT = 'MUSEUM OF ELECTRONIC GAMES & ART'
TEXT_BASE, TEXT_X0, TEXT_X1, PEN = 50.3, 0.5, 199.5, 1.0
BLACK, MAROON = '#000000', '#680040'


def grid():
    from PIL import Image
    im = Image.open(SRC).convert('RGBA')
    cells = []
    for r in range(ROWS):
        for c in range(COLS):
            x, y = int(PITCH * c + 3), int(PITCH * r + 3)
            red, g, b, a = im.getpixel((x, y))
            ink = (1 - (red * 0.3 + g * 0.59 + b * 0.11) / 255) * a / 255
            if ink > 0.5:
                cells.append((r, c, MAROON if red > g + 30 else BLACK))
    return cells


def main():
    cells = grid()
    off = (PITCH - BLOCK) / 2
    rects = {BLACK: [], MAROON: []}
    for r, c, col in cells:
        x, y = PITCH * c + off, PITCH * r + off
        rects[col].append('M%.3f %.3fh%.3fv%.3fh%.3fz' % (x, y, BLOCK, BLOCK, -BLOCK))
    # text: size so that the stroked line spans TEXT_X0..TEXT_X1
    span = TEXT_X1 - TEXT_X0 - PEN
    size = span / (len(TEXT) - 1 / 3)
    lines = font.text(TEXT, TEXT_X0 + PEN / 2, TEXT_BASE - PEN / 2, size, anchor='start', vcentre=False)
    d = ' '.join('M' + ' L'.join('%.3f %.3f' % p for p in pl) for pl in lines if len(pl) > 1)
    body = ('<svg xmlns="http://www.w3.org/2000/svg" width="200" height="52" viewBox="0 0 200 52">\n'
            '<path id="text" fill="none" stroke="%s" stroke-width="%.2f" stroke-linejoin="miter" '
            'stroke-linecap="square" d="%s"/>\n</svg>\n' % (MAROON, PEN, d))
    with tempfile.TemporaryDirectory() as td:
        a, b = os.path.join(td, 'in.svg'), os.path.join(td, 'out.svg')
        open(a, 'w').write(body)
        subprocess.run(['inkscape', a, '--actions=select-by-id:text;object-stroke-to-path;path-union;'
                        'export-filename:%s;export-plain-svg;export-do' % b], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        t = open(b).read()
    import re
    paths = re.findall(r'<path\b[^>]*\bd="([^"]+)"', t)
    if not paths:
        sys.exit('inkscape produced no path')
    tf = re.search(r'<path\b[^>]*transform="([^"]+)"', t)
    if tf:
        sys.exit('unexpected transform on the text path: %s' % tf.group(1))
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!-- M.E.G.A. e.V. (Museum of Electronic Games & Art) logo, vector rebuild for laser etching.',
           '     Source: https://www.m-e-g-a.org/wp-content/uploads/2012/06/mlogo.png (downloaded 2026-11-27,',
           '     copy in logos/src/mlogo.png). Generated by tools/make_mega_ev_logo.py: do not edit by hand.',
           '     Units = source pixels; the case generator scales it and etches every fill black. -->',
           '<svg xmlns="http://www.w3.org/2000/svg" width="200mm" height="52mm" viewBox="0 0 200 52">',
           '<path fill="%s" d="%s"/>' % (BLACK, ' '.join(rects[BLACK])),
           '<path fill="%s" d="%s"/>' % (MAROON, ' '.join(rects[MAROON]))]
    for p in paths:
        out.append('<path fill="%s" d="%s"/>' % (MAROON, p))
    out.append('</svg>')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('wrote %s: %d blocks, text size %.2f px' % (OUT, len(cells), size))


if __name__ == '__main__':
    main()
