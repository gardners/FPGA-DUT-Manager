def text_width(s, size):
    return max(len(s) * size - size / 3, 0)


def text(s, u, v, size, anchor='middle', vcentre=True):
    """Polylines for string s; (u, v) = anchor point, v = vertical centre of
    the capitals (vcentre) or the baseline. size = capital height (mm)."""
    k = size / 6.0
    w = text_width(s, size)
    if anchor == 'middle':
        u0 = u - w / 2
    elif anchor == 'end':
        u0 = u - w
    else:
        u0 = u
    base = v + size / 2 if vcentre else v
    out = []
    for i, ch in enumerate(s):
        g = GLYPHS.get(ch, GLYPHS.get(ch.upper(), [[(0, 0), (4, 0), (4, 6), (0, 6), (0, 0)]]))
        ox = u0 + i * size
        for stroke in g:
            out.append([(ox + x * k, base - y * k) for (x, y) in stroke])
    return out


def text_vertical(s, u, v, size):
    """Text reading bottom-to-top, centred on (u, v)."""
    lines = text(s, 0, 0, size)
    return [[(u + y, v - x) for (x, y) in pl] for pl in lines]
