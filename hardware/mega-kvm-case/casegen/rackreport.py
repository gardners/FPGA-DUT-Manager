"""Write the rack outputs (out/rack/...) and out/fit-report.md (issue 0051)."""
import importlib.util
import os
import shutil

from . import layout, nest, rack, svgout

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_footprint(cfg):
    path = os.path.join(HERE, cfg.FOOTPRINT)
    spec = importlib.util.spec_from_file_location('mega65_footprint', path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def preview(svg_path, png, out_png, writer):
    """Render a copy with the reference layer visible (battens, placeholders)."""
    old, oldc = svgout.SHOW_REF, svgout.CUT
    svgout.SHOW_REF = True
    svgout.CUT = oldc.replace('stroke-width:0.01', 'stroke-width:0.35')    # visible in the render only
    tmp = out_png[:-4] + '.svg'
    try:
        writer(tmp)
    finally:
        svgout.SHOW_REF, svgout.CUT = old, oldc
    r = png(tmp)
    os.remove(tmp)
    return r


def write_all(cfg, boards, OUT, png, files):
    fp = load_footprint(cfg)
    res = rack.build(cfg, boards, fp)
    g, kv = res['geo'], res['kvm']
    base = os.path.join(OUT, 'rack')
    k = cfg.RACK_KERF
    for p in res['parts']:
        path = os.path.join(base, 'parts', p.name + '.svg')
        svgout.write_panel(p, path, k)
        files.append(path)
    for name, frag in kv['frags']:
        path = os.path.join(base, 'fragments', name + '.svg')
        svgout.write_panel(frag, path, k)
        files.append(path)
    res['sheets'] = {}
    for mat, sheet in cfg.RACK_SHEETS.items():
        sheets, too_big = nest.nest(res['parts'], sheet, cfg.SHEET_MARGIN, cfg.NEST_GAP)
        res['sheets'][mat] = (len(sheets), too_big)
        for i, sh in enumerate(sheets):
            path = os.path.join(base, 'sheets', '%s-%dx%d-%d.svg' % (mat, sheet[0], sheet[1], i + 1))
            svgout.write_sheet(sh, path, k, 'rack parts, %s sheet %d of %d' % (mat, i + 1, len(sheets)))
            files.append(path)
        for name in too_big:
            res['problems'].append('%s sheet: %s does not fit' % (mat, name))
    # drawings
    ev = os.path.join(base, 'rack-elevation.svg')
    rack.elevation(g, kv, ev)
    files.append(ev)
    pg = png(ev, 100)
    if pg:
        files.append(pg)
    tv = os.path.join(base, 'kvm-topview.svg')
    layout.topview(tv, 'KVM unit top view (deck %.0f x %.0f mm, %dRU)' % (g.W, kv['D'], cfg.KVM['ru']), g.W, kv['D'],
                   [b for b in kv['boxes'] if b.inside], 0.0,
                   notes=['dashed red = cable/plug allowance (soft); battens 25 mm under both deck edges'] +
                   ['PROBLEM: ' + p for p in res['problems'] if p.startswith('KVM')][:6])
    files.append(tv)
    pg = png(tv)
    if pg:
        files.append(pg)
    for p in res['parts']:
        if p.name in ('shelf-deck', 'fan-plate', 'kvm-front', 'kvm-rear', 'kvm-deck'):
            out_png = os.path.join(base, 'preview', p.name + '.png')
            os.makedirs(os.path.dirname(out_png), exist_ok=True)
            r = preview(None, png, out_png, lambda path, p=p: svgout.write_panel(p, path, 0.0))
            if r:
                files.append(r)
    res['report'] = report(cfg, fp, res, boards, files, OUT)
    return res


def report(cfg, fp, res, boards, files, OUT):
    g, kv = res['geo'], res['kvm']
    RU = g.RU
    L = []
    w = L.append
    lay = cfg.RACK['layout']
    n_sh = lay.count('shelf')
    tot = n_sh * RU + kv['H']
    w('# MEGA-KVM rack: fit report (generated by build.py, do not edit)')
    w('')
    w('Issue 0051. Layout (bottom to top): %s = **%.2f mm = %.0fRU**. Material: %.0f mm ply, kerf %.2f mm. '
      'Fan clearance mode: **%s**.' % (', '.join(lay), tot, tot / RU, g.T, cfg.RACK_KERF, g.mode))
    w('Options A and B (the single 1RU box) are in `fit-report-options-AB.md` and are no longer developed.')
    w('')
    if res['problems']:
        w('## Conflicts / problems (%d)' % len(res['problems']))
        w('')
        for p in res['problems']:
            w('* ' + p)
    else:
        w('## Conflicts / problems: none')
    w('')
    w('## Inputs and their sources')
    w('')
    for nm, blk in (('MEGA65 board', fp.BOARD), ('floppy', fp.FLOPPY), ('Cart64out Rev.1', fp.CART64OUT),
                    ('official expansions', fp.EXPANSIONS)):
        w('* **%s**: %s (%s).' % (nm, blk['source'], 'holes cut' if blk['cut'] else 'NOT cut: reference layer only'))
    w('* Front-panel PCB: `%s` (%s).' % (cfg.KVM['front_holes'], 'found' if os.path.exists(os.path.join(HERE, cfg.KVM['front_holes'])) else 'NOT FOUND'))
    w('* Power boards: %s.' % ', '.join('%s = %s' % (k2, v['src'] if v else 'NOT FOUND (config fallback)') for k2, v in boards.items()))
    w('* Logos: ' + '; '.join(sorted(set(res['logo_notes']))) + '.')
    w('* Cross-checks: MEGA65 holes: Trenz DIM drawing vs the rugged case agree within 0.8 mm (rear-right hole y 93.8 '
      'vs 93.0; front row y 4.88 vs 5.0); the DIM values are used. Cart64out holes: Eagle .brd and DXF agree exactly '
      '(Ø3.302 at (16,4) (16,58) (71,4) (71,58)); the DXF outline is 97 x 62 including a 12 mm tongue (body 85 mm, '
      'not 86). The Cart64out insertion depth (tongue tip at board y %.1f) comes from the rugged case\'s single '
      'breakout support hole, which lands exactly on Cart64out hole (71, 58).' % fp.CART64OUT['tip_y'])
    w('')
    w('## Heights (1RU pitch)')
    w('')
    w('| Item | mm |')
    w('|---|---|')
    w('| batten (under the deck) | %.2f |' % g.BT)
    w('| deck | %.2f |' % g.T)
    w('| deck top above the slot bottom | %.2f |' % g.top)
    w('| deck top -> next deck underside (between the battens) | **%.2f** |' % g.clear_mid)
    w('| deck top -> next shelf\'s battens (25 mm edge strips) | **%.2f** |' % g.clear_edge)
    w('')
    w('| Part on a shelf | height above the deck | limit (%.0f mm air gap) | ok | note |' % cfg.SHELF['clear_top'])
    w('|---|---|---|---|---|')
    for name, hh, lim, note in res['heights']:
        w('| %s | %.1f | %.1f | %s | %s |' % (name, hh, lim, 'yes' if hh <= lim else '**NO**', note))
    w('')
    w('Edge strips (x < %.0f and x > %.0f on the deck): parts there must stay below %.1f mm. The deck has '
      'etched dashed lines at the battens\' inner edges.' % (g.BT, g.W - g.BT, res['lim_e']))
    w('')
    w('MEGA65 tall parts against the next shelf (the drawers have no top: the next shelf\'s deck and battens are '
      'the top). Heights above the deck = %.1f spacer + 1.6 PCB + part.' % fp.BOARD['standoff'])
    w('')
    w('| Part | deck x | height above the deck | margin to the next deck | margin to a batten above (if it were under one) | '
      'lateral gap to the nearer batten | ok | source |')
    w('|---|---|---|---|---|---|---|---|')
    for name, x0, x1, hh, md, me, side, under, src in res['tall']:
        ok = hh <= (res['lim_e'] if under else res['lim'])
        w('| %s | %.1f-%.1f | %.1f | %.1f | %s | %s | %s | %s |' % (
            name, x0, x1, hh, md, ('%.1f' % me) if under else '(%.1f, not under one)' % me,
            ('%.1f' % side) if side >= 0 else '**under (%.1f)**' % side, 'yes' if ok else '**NO**', src))
    w('')
    w('## Widths')
    w('')
    w('| Item | mm |')
    w('|---|---|')
    w('| between the rack posts | %.1f |' % cfg.RACK['post_opening'])
    R = getattr(cfg, 'RAILS', None)
    if R:
        w('| slide rails, per side (%s: measure) | %.1f |' % (R['status'], R['thick']))
    w('| deck (between the rails) | %.1f |' % g.W)
    w('| full height between the battens | **%.1f** |' % (g.W - 2 * g.BT))
    w('| MEGA65 board (%.0f) + gap + floppy (%.1f) | %.1f |' % (fp.BOARD['w'], fp.FLOPPY['w'], g.span))
    w('| board left edge / floppy centre (deck x) | %.1f / %s |' % (g.bx, '%.1f' % g.fx if g.fx else '-'))
    F = cfg.FAN_PLATE
    fw = g.fans[-1]['x1'] - g.fans[0]['x0']
    w('| %d x %d mm fans + gaps on the fan plate | %.1f (x %.1f-%.1f) |' % (F['count'], F['fan'], fw, g.fans[0]['x0'], g.fans[-1]['x1']))
    w('| fan plate / KVM front face | %.1f |' % cfg.RACK['face_width'])
    w('')
    w('## Shelf deck')
    w('')
    w('* Deck %.0f x %.0f mm: front allowance %.0f + MEGA65 board %.0f + rear space %.0f.' % (
        g.W, g.D, g.by, fp.BOARD['d'], cfg.SHELF['rear_space']))
    w('* Cart64out lies flat behind the expansion port: tongue tip at deck y %.1f, rear edge at y %.1f; the '
      'strain-relief bar stands at y %.1f.' % (g.by + fp.CART64OUT['tip_y'], res['cart_end'], res['bar_y']))
    if g.notches:
        w('* Fan notches: %s, %.0f mm deep (fan %.0f + %.0f).' % (
            ', '.join('x %.1f-%.1f' % n for n in g.notches), g.nd, g.fspec['thick'], cfg.SHELF['notch_extra']))
    else:
        w('* Fan notches: **none** (plain rectangular deck; the fan plate\'s low fans start %.1f mm above the '
          'carrier\'s deck top).' % (min(f['z0'] for f in g.fans) - g.top))
    if g.mode == 'notch':
        w('* Notch mode: all shelves of a group sit flush. On the **three other shelves of each group the battens '
          'start %.0f mm behind the deck front** (cut them %.0f mm shorter), so the carrier\'s gussets fit under '
          'their decks. The deck\'s batten screw holes start behind that point; the carrier also uses the two '
          'gusset pilot holes per side.' % (g.batten_front_other, g.batten_front_other))
    else:
        w('* Set-back mode: the other shelves of a group are set back %.0f mm on their rails (minimum %.0f: fan '
          'bodies and gussets).' % (g.setback, g.setback_need))
    w('* Long server rails: battens may be longer than the deck (to the rails\' inner-member length); the deck '
      'only fixes the front %.0f mm.' % g.D)
    w('')
    w('## Fan plate (%dRU = %.1f mm) clearances within a group' % (F['ru'], g.FH))
    w('')
    w('Fans (z above the bottom of the carrier shelf\'s slot): ' + '; '.join(
        'fan %d %s x %.1f-%.1f z %.1f-%.1f' % (f['i'] + 1, f['where'], f['x0'], f['x1'], f['z0'], f['z1']) for f in g.fans) + '.')
    w('Gussets: %.0f mm tall x %.0f mm long on the carrier deck over each batten.' % (g.gus['h'], g.gus['l']))
    w('')
    w('| Item | nearest part of the group | clearance mm | direction |')
    w('|---|---|---|---|')
    for name, it, best in res['group_rows']:
        if best:
            w('| %s | %s | %.1f | %s |' % (name, best[1], best[0], best[2]))
    w('')
    w('## KVM unit (%dRU = %.2f mm, on slides)' % (cfg.KVM['ru'], kv['H']))
    w('')
    K = cfg.KVM
    px0, py0, pmw, pmd, pzt = kv['pm']
    w('* Deck %.0f x %.0f mm (open top; the next unit sits %.2f mm up). Front zone %.0f mm deep (fans, display '
      'PCB + LCD, rocker).' % (g.W, kv['D'], kv['H'], kv['zone_d']))
    w('* Depth budget: power board front edge at y %.0f (behind the front panel) + board %.1f + cable gap %.0f '
      '(DUT leads cross here) + RJ45 patch clearance %.0f + Mimas %.0f = %.0f mm. All units together: shelves '
      '%.0f mm, KVM %.0f mm, rack %.0f mm between the posts (MEASURE).' % (
          py0, pmd, K['cable_gap'], cfg.MIMAS['rj45_plug_clear'], cfg.MIMAS['d'], kv['D'], g.D, kv['D'],
          cfg.RACK['depth_posts']))
    w('* Power board (owner round 12, %.0f x %.1f mm) at x %.0f-%.0f, y %.1f-%.1f, top %.1f mm above the slot '
      'bottom. The input connectors along its front edge are plugged from the open top: %.0f mm of free height '
      'above the board over its front %.0f mm (checked as the "input plugs" box), and %.1f mm to the next unit\'s '
      'battens above that.' % (pmw, pmd, px0, px0 + pmw, py0, py0 + pmd, pzt, K['plug_clear'], K['plug_strip'],
                                kv['H'] - (pzt + K['plug_clear'])))
    w('* GS105 at x %.0f-%.0f beside the board. Cable routes (dashed in the top view): DUT leads from the '
      'terminals on the board\'s rear edge (y %.1f) across the cable gap to the bulkhead/DUT-power column at the '
      'rear left (x %.0f-%.0f, the bays start at x %.1f); Mimas Mini-Fit leads back to the bays; the GS105 jack '
      'lead sideways to the switch. Tie-slot pairs hold the DUT bundle in the cable gap.' % (
          kv['gs'][0], kv['gs'][0] + cfg.GS105['w'], kv['yr'], kv['col'][0], kv['col'][1], kv['bay_x0']))
    fz = kv['fans'][0][1] if kv['fans'] else 0.0
    w('* Front panel width budget behind the face: fans %d x %d mm (x %.1f-%.1f, z %.1f-%.1f), display column '
      '%.1f mm (x %.1f-%.1f): needs %.1f of %.1f mm.' % (
          K['fan_count'], K['fan'], kv['fans_x0'], kv['fans_end'], fz - K['fan'] / 2, fz + K['fan'] / 2,
          kv['right_w'], kv['pcb_x0'], kv['pcb_x0'] + kv['right_w'], kv['width_need'], g.W))
    w('* Display column: PCB %.0f x %.0f mm at z %.1f-%.1f (x %.1f-%.1f), read from panel-holes.json; the '
      'MEGA-KVM etch and the logos under it.' % (
          kv['pcb'][2], kv['pcb'][3], kv['pcb'][1], kv['pcb'][1] + kv['pcb'][3], kv['pcb'][0], kv['pcb'][0] + kv['pcb'][2]))
    if kv['fan_cross_deck']:
        w('* Fans cross the deck: they reach %.1f mm below the deck top, through %s in the deck front (%s), '
          'between the front gussets; nearest under-deck part (gusset/batten) %.1f mm away sideways. Fan bodies '
          '(%.0f mm deep) end at y %.0f; the power board starts at y %.0f.' % (
              g.top - (fz - K['fan'] / 2),
              'one notch' if len(kv['notches']) == 1 else '%d notches' % len(kv['notches']),
              ', '.join('x %.0f-%.0f, %.0f mm deep' % n for n in kv['notches']),
              kv['fan_under_gap'] if kv['fan_under_gap'] is not None else float('nan'),
              cfg.FANS[K['fan']]['thick'], cfg.FANS[K['fan']]['thick'], kv['pm'][1]))
    else:
        w('* Fans clear the deck (top-aligned, no notch).')
    for what, a0, b0, a1, b1 in kv['etched']:
        w('* Etched: %s at x %.0f-%.0f, z %.1f-%.1f (checked against the fans, display PCB, rocker and '
          'screws).' % (what, a0, a1, b0, b1))
    w('* Rocker: %s (deck x %.1f, z %.1f).' % (K['rocker_pos'], kv['rock'][0], kv['rock'][1]))
    w('* Rear plate %.0f x %.1f mm (seen from the rear): bays %.1f mm at the left, the bulkhead/DUT power column at '
      'the right (= deck left, behind the DUT terminals); %.1f mm spare. The keyboard feed-through sits above the '
      'column; vent slots fill the upper part.' % (
          g.W, kv['Hr'], kv['bays_w'], kv['rear_free']))
    for n in res['notes']:
        w('* ' + n)
    w('* Gussets: 4 under the deck against the battens\' inner faces (%.0f x %.0f mm), front and rear.' % (
        K['gusset']['h'], K['gusset']['l']))
    w('')
    w('| Part | nearest neighbour (same height band) | gap mm | headroom to the unit top mm |')
    w('|---|---|---|---|')
    for name, best, top in res['kclear']:
        w('| %s | %s | %s | %.1f |' % (name, best[1] if best else '-', '%.1f' % best[0] if best else '-', top))
    w('')
    w('## Parts and sheets')
    w('')
    w('| Part | size mm | qty |')
    w('|---|---|---|')
    for p in res['parts']:
        sw, sh = p.size()
        w('| %s | %.1f x %.1f | %d |' % (p.name, sw, sh, p.qty))
    w('')
    w('* Not cut: 25 x 25 timber battens: 2 per shelf and 2 for the KVM, deck depth long%s.' % (
        (' (%d of them %.0f mm shorter at the front, notch mode)' % (2 * (n_sh - n_sh // cfg.RACK['group']), g.batten_front_other))
        if g.mode == 'notch' else ''))
    for mat, (n, tb) in res['sheets'].items():
        w('* %s %dx%d: %d sheet(s)%s.' % (mat, cfg.RACK_SHEETS[mat][0], cfg.RACK_SHEETS[mat][1], n,
                                         (' (does not fit: %s)' % ', '.join(tb)) if tb else ''))
    w('')
    w('## Generated files')
    w('')
    for f in sorted(set(files)):
        if '/rack/' in f:
            w('* `%s`' % os.path.relpath(f, HERE))
    path = os.path.join(OUT, 'fit-report.md')
    with open(path, 'w') as fh:
        fh.write('\n'.join(L) + '\n')
    return path
