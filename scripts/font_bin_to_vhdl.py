"""Generate hdl/src/video/font8x16_pkg.vhd from third_party/fonts/cp437-8x16.bin.

The binary is hardweb's interlaced layout: even glyph rows at code*8 + row/2,
odd rows at 2048 + code*8 + row/2 (bit 7 = leftmost pixel). SIL OFL 1.1.
"""
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
data = (root / "third_party/fonts/cp437-8x16.bin").read_bytes()
assert len(data) == 4096
out = ["-- GENERATED by scripts/font_bin_to_vhdl.py from third_party/fonts/cp437-8x16.bin",
       "-- Terminus-derived CP437 8x16 font, SIL Open Font License 1.1.",
       "-- Interlaced layout: address = row(0) & code(7:0) & row(3:1).",
       "library ieee;", "use ieee.std_logic_1164.all;", "",
       "package font8x16_pkg is",
       "  type font_array_t is array (0 to 4095) of std_logic_vector(7 downto 0);",
       "  constant FONT8X16 : font_array_t := ("]
for i in range(0, 4096, 8):
    sep = "," if i + 8 < 4096 else ""
    out.append("    " + ", ".join('x"%02X"' % b for b in data[i:i + 8]) + sep)
out += ["  );", "end package;", ""]
(root / "hdl/src/video/font8x16_pkg.vhd").write_text("\n".join(out))
